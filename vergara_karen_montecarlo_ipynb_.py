def calcular_puntos(dados, categoria, comodin=False):
    conteo = Counter(dados)
    total = sum(dados)
    valores = set(dados)

    if categoria in CATEGORIAS_MC[:6]:
        numero = CATEGORIAS_MC.index(categoria) + 1
        return conteo[numero] * numero

    if categoria == "Trío":
        return total if max(conteo.values()) >= 3 else 0

    if categoria == "Póker":
        return total if max(conteo.values()) >= 4 else 0

    if categoria == "Full house":
        return 25 if comodin or sorted(conteo.values()) == [2, 3] else 0

    if categoria == "Escalera corta":
        secuencias = [
            {1, 2, 3, 4}, {2, 3, 4, 5}, {3, 4, 5, 6}
        ]
        return 30 if comodin or any(
            s.issubset(valores) for s in secuencias
        ) else 0

    if categoria == "Escalera larga":
        escaleras = [
            {1, 2, 3, 4, 5}, {2, 3, 4, 5, 6}
        ]
        return 40 if comodin or valores in escaleras else 0

    if categoria == "Suerte":
        return total

    if categoria == "Yahtzee":
        return 50 if len(conteo) == 1 else 0

    return 0


def lanzar_turno(rng, frecuencia_caras):
    """Realiza hasta tres lanzamientos de cinco dados."""
    dados = [rng.randint(1, 6) for _ in range(5)]

    for valor in dados:
        frecuencia_caras[valor - 1] += 1

    for _ in range(2):
        conteo = Counter(dados)

        # Conservar la cara que más se repite
        objetivo = max(
            range(1, 7),
            key=lambda cara: (conteo[cara], cara)
        )

        for i in range(5):
            if dados[i] != objetivo:
                dados[i] = rng.randint(1, 6)
                frecuencia_caras[dados[i] - 1] += 1

    return dados


def jugar_partida(rng, frecuencia_caras):
    """Simula una partida de 13 turnos para dos jugadores."""
    puntos = [{}, {}]
    bonos_yahtzee = [0, 0]

    for _ in range(13):
        for jugador in range(2):
            dados = lanzar_turno(rng, frecuencia_caras)
            registro = puntos[jugador]

            disponibles = [
                c for c in CATEGORIAS_MC if c not in registro
            ]

            es_yahtzee = len(set(dados)) == 1
            extra = (
                es_yahtzee
                and registro.get("Yahtzee") == 50
            )

            superior = CATEGORIAS_MC[dados[0] - 1]
            comodin = extra and superior in registro

            # Regla de asignación forzosa
            if extra and superior in disponibles:
                disponibles = [superior]

            # Elegir la mejor puntuación inmediata
            categoria = max(
                disponibles,
                key=lambda c: calcular_puntos(
                    dados, c, comodin
                )
            )

            registro[categoria] = calcular_puntos(
                dados, categoria, comodin
            )

            if extra:
                bonos_yahtzee[jugador] += 100

    totales = []

    for jugador in range(2):
        subtotal = sum(
            puntos[jugador].get(c, 0)
            for c in CATEGORIAS_MC[:6]
        )

        bono_superior = 35 if subtotal >= 63 else 0

        total = (
            sum(puntos[jugador].values())
            + bono_superior
            + bonos_yahtzee[jugador]
        )

        totales.append(total)

    return totales


def simular_montecarlo(n_partidas, semilla=42):
    """Ejecuta partidas reproducibles de Montecarlo."""
    rng = random.Random(semilla)

    resultados = np.zeros((n_partidas, 2), dtype=int)
    frecuencia_caras = np.zeros(6, dtype=int)

    for i in range(n_partidas):
        resultados[i] = jugar_partida(
            rng, frecuencia_caras
        )

    victorias_1 = int(np.sum(
        resultados[:, 0] > resultados[:, 1]
    ))
    victorias_2 = int(np.sum(
        resultados[:, 1] > resultados[:, 0]
    ))
    empates = n_partidas - victorias_1 - victorias_2

    print("RESULTADOS DE MONTECARLO")
    print("-" * 40)
    print(f"Partidas realizadas: {n_partidas:,}")
    print(f"Promedio Jugador 1: {resultados[:,0].mean():.2f}")
    print(f"Promedio Jugador 2: {resultados[:,1].mean():.2f}")
    print(f"Victorias Jugador 1: {victorias_1}")
    print(f"Victorias Jugador 2: {victorias_2}")
    print(f"Empates: {empates}")
    print("-" * 40)

    total_lanzamientos = frecuencia_caras.sum()

    print("\nFRECUENCIAS DE LOS DADOS")
    for cara in range(1, 7):
        porcentaje = (
            frecuencia_caras[cara - 1]
            / total_lanzamientos * 100
        )
        print(f"Cara {cara}: {porcentaje:.3f}%")

    # Gráfica 1: convergencia de promedios
    x = np.arange(1, n_partidas + 1)
    promedio_1 = np.cumsum(resultados[:, 0]) / x
    promedio_2 = np.cumsum(resultados[:, 1]) / x

    plt.figure(figsize=(10, 5))
    plt.plot(x, promedio_1, label="Jugador 1")
    plt.plot(x, promedio_2, label="Jugador 2")
    plt.title("Montecarlo: convergencia del puntaje promedio")
    plt.xlabel("Número de partidas")
    plt.ylabel("Puntuación promedio")
    plt.legend()
    plt.grid(alpha=0.3)
    plt.show()

    # Gráfica 2: frecuencias de los dados
    porcentajes = frecuencia_caras / total_lanzamientos * 100

    plt.figure(figsize=(9, 5))
    plt.bar(range(1, 7), porcentajes)
    plt.axhline(
        100 / 6,
        color="red",
        linestyle="--",
        label="Probabilidad teórica: 16.67%"
    )
    plt.title("Distribución de las caras de los dados")
    plt.xlabel("Cara del dado")
    plt.ylabel("Frecuencia relativa (%)")
    plt.xticks(range(1, 7))
    plt.legend()
    plt.grid(axis="y", alpha=0.3)
    plt.show()

    return resultados, frecuencia_caras


