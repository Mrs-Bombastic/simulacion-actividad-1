class JuegoYahtzee:
    def __init__(self):
        self.jugadores = ["Jugador 1", "Jugador 2"]
        self.puntos = [{}, {}]
        self.bonos_yahtzee = [0, 0]
        self.turno = 0
        self.ronda = 1
        self.lanzamientos = 0
        self.dados = [1] * 5
        self.bloqueados = [False] * 5
        self.terminado = False

        self.titulo = widgets.HTML()
        self.mensaje = widgets.HTML()
        self.tabla = widgets.HTML()

        self.botones_dados = [
            widgets.ToggleButton(
                description="?",
                layout=widgets.Layout(width="65px", height="60px"),
                style={"font_weight": "bold"}
            )
            for _ in range(5)
        ]

        for i, boton in enumerate(self.botones_dados):
            boton.observe(
                lambda cambio, pos=i: self.conservar(cambio, pos),
                names="value"
            )

        self.boton_lanzar = widgets.Button(
            description="🎲 LANZAR DADOS",
            button_style="success",
            layout=widgets.Layout(width="220px", height="45px")
        )
        self.boton_lanzar.on_click(self.lanzar)

        self.selector = widgets.Dropdown(
            options=CATEGORIAS,
            description="Categoría:",
            layout=widgets.Layout(width="280px")
        )

        self.boton_puntos = widgets.Button(
            description="Registrar puntos",
            button_style="info",
            layout=widgets.Layout(width="180px")
        )
        self.boton_puntos.on_click(self.registrar)

        self.actualizar()

        display(
            self.titulo,
            widgets.HBox(self.botones_dados),
            self.boton_lanzar,
            self.selector,
            self.boton_puntos,
            self.mensaje,
            self.tabla
        )

    def puntuar(self, categoria, comodin=False):
        conteo = Counter(self.dados)
        valores = sorted(set(self.dados))
        total = sum(self.dados)

        if categoria in CATEGORIAS[:6]:
            numero = CATEGORIAS.index(categoria) + 1
            return conteo[numero] * numero

        if categoria == "Trío":
            return total if max(conteo.values()) >= 3 else 0

        if categoria == "Póker":
            return total if max(conteo.values()) >= 4 else 0

        if categoria == "Full house":
            return 25 if comodin or sorted(conteo.values()) == [2, 3] else 0

        if categoria == "Escalera corta":
            secuencias = [
                {1, 2, 3, 4}, {2, 3, 4, 5}, {3, 4, 5, 6}
            ]
            return 30 if comodin or any(
                sec.issubset(valores) for sec in secuencias
            ) else 0

        if categoria == "Escalera larga":
            return 40 if comodin or valores in (
                [1, 2, 3, 4, 5], [2, 3, 4, 5, 6]
            ) else 0

        if categoria == "Suerte":
            return total

        if categoria == "Yahtzee":
            return 50 if len(conteo) == 1 else 0

        return 0

    def conservar(self, cambio, pos):
        if cambio["name"] != "value":
            return

        if self.lanzamientos == 0 or self.terminado:
            return

        self.bloqueados[pos] = cambio["new"]
        self.botones_dados[pos].button_style = (
            "warning" if cambio["new"] else ""
        )

    def lanzar(self, boton):
        if self.terminado or self.lanzamientos >= 3:
            return

        for i in range(5):
            if not self.bloqueados[i]:
                self.dados[i] = random.randint(1, 6)

        self.lanzamientos += 1
        self.actualizar()

    def categorias_permitidas(self):
        disponibles = [
            c for c in CATEGORIAS
            if c not in self.puntos[self.turno]
        ]

        es_yahtzee = len(set(self.dados)) == 1
        yahtzee_50 = self.puntos[self.turno].get("Yahtzee") == 50

        if es_yahtzee and yahtzee_50:
            superior = CATEGORIAS[self.dados[0] - 1]
            if superior in disponibles:
                return [superior]

        return disponibles

    def registrar(self, boton):
        if self.terminado or self.lanzamientos == 0:
            self.mensaje.value = "<b>Primero debes lanzar los dados.</b>"
            return

        categoria = self.selector.value
        disponibles = self.categorias_permitidas()

        if categoria not in disponibles:
            self.mensaje.value = "<b>Selecciona una categoría disponible.</b>"
            return

        es_yahtzee = len(set(self.dados)) == 1
        yahtzee_50 = self.puntos[self.turno].get("Yahtzee") == 50
        extra = es_yahtzee and yahtzee_50

        superior = CATEGORIAS[self.dados[0] - 1]
        comodin = extra and superior in self.puntos[self.turno]

        puntos = self.puntuar(categoria, comodin)

        self.puntos[self.turno][categoria] = puntos

        if extra:
            self.bonos_yahtzee[self.turno] += 100

        if self.turno == 1:
            self.ronda += 1

        self.turno = 1 - self.turno
        self.lanzamientos = 0
        self.dados = [1] * 5
        self.bloqueados = [False] * 5

        for boton_dado in self.botones_dados:
            boton_dado.value = False
            boton_dado.button_style = ""

        self.terminado = all(
            len(p) == 13 for p in self.puntos
        )

        self.actualizar()

    def total_jugador(self, jugador):
        superior = sum(
            self.puntos[jugador].get(c, 0)
            for c in CATEGORIAS[:6]
        )

        bono = 35 if superior >= 63 else 0

        return (
            sum(self.puntos[jugador].values())
            + bono
            + self.bonos_yahtzee[jugador]
        )

    def actualizar(self):
        self.titulo.value = (
            f"<h2>🎲 YAHTZEE - RONDA {min(self.ronda, 13)}/13</h2>"
            f"<h3>Turno: {self.jugadores[self.turno]}</h3>"
        )

        for i, boton in enumerate(self.botones_dados):
            boton.description = (
                str(self.dados[i]) if self.lanzamientos else "?"
            )

        disponibles = (
            self.categorias_permitidas()
            if not self.terminado else []
        )

        self.selector.options = disponibles
        self.boton_lanzar.disabled = (
            self.terminado or self.lanzamientos >= 3
        )
        self.boton_puntos.disabled = (
            self.terminado or self.lanzamientos == 0
        )

        filas = ""
        for categoria in CATEGORIAS:
            valores = [
                str(p[categoria]) if categoria in p else "-"
                for p in self.puntos
            ]

            filas += (
                "<tr>"
                f"<td>{categoria}</td>"
                f"<td>{valores[0]}</td>"
                f"<td>{valores[1]}</td>"
                "</tr>"
            )

        filas += (
            "<tr><th>Bonos Yahtzee</th>"
            f"<th>{self.bonos_yahtzee[0]}</th>"
            f"<th>{self.bonos_yahtzee[1]}</th></tr>"
        )

        filas += (
            "<tr><th>TOTAL</th>"
            f"<th>{self.total_jugador(0)}</th>"
            f"<th>{self.total_jugador(1)}</th></tr>"
        )

        self.tabla.value = (
            "<table style='border-collapse:collapse;width:450px'>"
            "<tr><th>Categoría</th>"
            "<th>Jugador 1</th><th>Jugador 2</th></tr>"
            f"{filas}</table>"
            "<style>td,th{border:1px solid gray;"
            "padding:6px;text-align:center}</style>"
        )

        if self.terminado:
            a = self.total_jugador(0)
            b = self.total_jugador(1)

            ganador = (
                "Jugador 1" if a > b
                else "Jugador 2" if b > a
                else "Empate"
            )

            self.mensaje.value = (
                f"<h2>🏆 FIN DEL JUEGO: {ganador}</h2>"
            )
        else:
            self.mensaje.value = (
                f"<p>Lanzamientos: {self.lanzamientos}/3</p>"
                "<p>Selecciona los dados para conservarlos "
                "y registra una categoría para terminar el turno.</p>"
            )

